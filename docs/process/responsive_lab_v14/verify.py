from pathlib import Path
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parent
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless=True)
 page=b.new_page(viewport={'width':1512,'height':945})
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto((ROOT/'index.html').as_uri())
 f=page.frame_locator('iframe')
 f.get_by_role('textbox',name='任务输入').fill('生成可交互原型')
 f.get_by_role('button',name='发送任务',exact=True).click()
 f.get_by_role('button',name='查看交互预览 →').wait_for()
 f.get_by_role('button',name='查看交互预览 →').click()
 f.get_by_role('button',name='开始创建 →').click()
 assert f.locator('#preview-result').inner_text().startswith('✓')
 page.locator('#state').select_option('error')
 f.get_by_role('button',name='重试任务').click()
 f.get_by_role('button',name='停止任务',exact=True).click()
 page.locator('#view').select_option('home')
 page.locator('#inputState').select_option('disabled')
 expect(f.get_by_role('textbox',name='任务输入')).to_be_disabled()
 page.locator('#inputState').select_option('default')
 page.locator('#radius').fill('8')
 expect(f.locator('.composer')).to_have_css('border-radius','8px')
 page.locator('#view').select_option('execution')
 page.locator('#state').select_option('running')
 page.get_by_role('button',name='桌面',exact=True).click()
 page.screenshot(path=str(ROOT/'desktop_lab.png'),full_page=True)
 page.goto((ROOT/'app.html').as_uri())
 page.evaluate("cfg.view='execution';cfg.state='running';render()")
 page.screenshot(path=str(ROOT/'desktop_app.png'),full_page=True)
 for width in [834,390]:
  page.goto((ROOT/'app.html').as_uri())
  page.set_viewport_size({'width':width,'height':945})
  page.evaluate("cfg.view='home';render()")
  assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
  page.screenshot(path=str(ROOT/f'home_{width}.png'),full_page=True)
  page.evaluate("cfg.view='execution';cfg.state='error';render()")
  page.screenshot(path=str(ROOT/f'execution_{width}.png'),full_page=True)
  page.get_by_role('button',name='关闭编辑器').click()
  assert page.locator('.composer').is_visible()
  page.get_by_role('button',name='展开导航').click()
  assert page.locator('.nav').is_visible()
  page.get_by_role('button',name='新建任务').click()
  page.get_by_role('button',name='收起导航').click()
  page.get_by_role('button',name='Auto ⌄').click()
  page.get_by_role('combobox',name='模型').select_option('GLM · 深度思考')
  page.get_by_role('button',name='完成',exact=True).click()
  expect(page.get_by_role('button',name='GLM · 深度思考 ⌄')).to_be_visible()
 assert not errors,errors
 print('PASS: task send/complete/stop/retry, preview, input disabled, radius, mobile navigation, model menu, desktop/tablet/mobile overflow; no page errors')
 b.close()
